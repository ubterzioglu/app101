#!/usr/bin/env node
// scripts/sync-local-env.mjs
//
// Reads the repo-root `.secret` file and produces `.env.local` containing
// ONLY the allowlisted public values, mapped to EXPO_PUBLIC_* names.
//
// Hard rules:
//  - Only allowlist keys are ever written.
//  - Forbidden (server-only) keys are NEVER written to .env.local.
//  - Missing required public values stop the process with a clear error.
//  - Real credential values are never printed to the log.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SECRET_PATH = resolve(ROOT, '.secret');
const ENV_LOCAL_PATH = resolve(ROOT, '.env.local');

// .secret key -> mobile EXPO_PUBLIC_* key
const ALLOWLIST = {
  SUPABASE_URL: 'EXPO_PUBLIC_SUPABASE_URL',
  SUPABASE_PUBLISHABLE_KEY: 'EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY',
  WEB_API_BASE_URL: 'EXPO_PUBLIC_WEB_API_BASE_URL',
};

// Keys that must never leak into the mobile bundle / .env.local.
const FORBIDDEN = new Set([
  'SUPABASE_SERVICE_ROLE_KEY',
  'SUPABASE_SECRET_KEY',
  'SUPABASE_SERVICE_KEY',
  'ADMIN_PANEL_PASSWORD',
  'CORNER_ADMIN_PASSWORD',
  'DEVUSER_AUTH_SECRET',
  'IP_HASH_SALT',
  'GOOGLE_PLACES_API_KEY',
]);

function fail(message) {
  console.error(`\n[env:sync] HATA: ${message}\n`);
  process.exit(1);
}

function unquote(raw) {
  const v = String(raw ?? '').trim();
  if (
    (v.startsWith('"') && v.endsWith('"')) ||
    (v.startsWith("'") && v.endsWith("'"))
  ) {
    return v.slice(1, -1).trim();
  }
  return v;
}

function parseDotenv(text) {
  /** @type {Record<string, string>} */
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue; // bare tokens (no '=') are ignored
    const key = trimmed.slice(0, eq).trim();
    const value = unquote(trimmed.slice(eq + 1));
    if (key) out[key] = value;
  }
  return out;
}

function main() {
  if (!existsSync(SECRET_PATH)) {
    fail(
      '.secret bulunamadı. Repo kökünde .secret oluşturun (bkz. .secret.example).'
    );
  }

  const parsed = parseDotenv(readFileSync(SECRET_PATH, 'utf8'));

  const missing = [];
  const lines = [];
  for (const [secretKey, expoKey] of Object.entries(ALLOWLIST)) {
    const value = parsed[secretKey];
    if (!value) {
      missing.push(secretKey);
      continue;
    }
    lines.push(`${expoKey}=${value}`);
  }

  if (missing.length > 0) {
    fail(
      `.secret içinde zorunlu public değer(ler) eksik: ${missing.join(', ')}`
    );
  }

  // Defensive: ensure no forbidden key ever ends up in the generated output.
  const forbiddenLeak = lines.find((line) =>
    [...FORBIDDEN].some((f) => line.includes(`${f}=`))
  );
  if (forbiddenLeak) {
    fail('Allowlist dışı (server-only) değer üretilen çıktıya sızdı. Durduruldu.');
  }

  const header =
    '# Generated by scripts/sync-local-env.mjs — do not edit by hand.\n' +
    '# Only allowlisted public values from .secret are written here.\n';
  writeFileSync(ENV_LOCAL_PATH, `${header}${lines.join('\n')}\n`, 'utf8');

  // Log key NAMES only, never values.
  console.log('[env:sync] .env.local oluşturuldu. Aktarılan public anahtarlar:');
  for (const expoKey of Object.values(ALLOWLIST)) {
    console.log(`  - ${expoKey}`);
  }
}

main();
